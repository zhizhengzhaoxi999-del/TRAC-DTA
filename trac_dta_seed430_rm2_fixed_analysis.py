# 5. Target-grouped training sampler
# =============================================================================
class TargetGroupedBatchSampler:
    """
    Target-aware packing without changing the effective epoch size.

    Each training interaction appears exactly once per epoch. Same-target chunks
    (<= group_size) are kept contiguous, but batches are packed by SAMPLE COUNT
    rather than by a fixed number of chunks. Therefore batches stay close to
    BATCH_SIZE and optimizer steps remain comparable to the original baseline.
    """
    def __init__(self, train_indices, prot_indices_cpu, batch_size, group_size, seed):
        self.train_indices = np.asarray(train_indices, dtype=np.int64)
        self.prot_indices = np.asarray(prot_indices_cpu, dtype=np.int64)
        self.batch_size = int(batch_size)
        self.group_size = int(group_size)
        self.seed = int(seed)
        self.by_target = defaultdict(list)
        for pair_idx in self.train_indices:
            self.by_target[int(self.prot_indices[pair_idx])].append(int(pair_idx))
        # Conservative upper bound; actual iter_epoch packing is deterministic in count.
        self._num_batches = math.ceil(len(self.train_indices) / max(1, self.batch_size - self.group_size + 1))

    def _make_batches(self, epoch):
        rng = np.random.default_rng(self.seed + 1009 * int(epoch))
        groups = []
        keys = list(self.by_target.keys())
        rng.shuffle(keys)
        for target in keys:
            ids = np.asarray(self.by_target[target], dtype=np.int64).copy()
            rng.shuffle(ids)
            chunks = [ids[i:i+self.group_size].tolist() for i in range(0, len(ids), self.group_size)]
            if len(chunks) >= 2 and len(chunks[-1]) == 1 and len(chunks[-2]) >= 3:
                chunks[-1].insert(0, chunks[-2].pop())
            groups.extend(chunks)
        rng.shuffle(groups)

        # Flatten target-homogeneous chunks, then slice by exact sample count.
        # A chunk can be split only at a batch boundary (at most group_size-1 samples),
        # which is a small price for preserving the baseline optimizer-step count.
        ordered = [idx for g in groups for idx in g]
        return [
            np.asarray(ordered[i:i + self.batch_size], dtype=np.int64)
            for i in range(0, len(ordered), self.batch_size)
        ]

    def __len__(self):
        return math.ceil(len(self.train_indices) / self.batch_size)

    def iter_epoch(self, epoch):
        yield from self._make_batches(epoch)


@torch.no_grad()
def build_inbatch_reference_indices(target_ids, k):
    """Select up to K random same-target references for every anchor."""
    B = int(target_ids.numel())
    if B == 0:
        raise ValueError("Empty training batch")

    same = target_ids[:, None].eq(target_ids[None, :])
    same.fill_diagonal_(False)

    kk = min(int(k), max(B - 1, 1))
    scores = torch.rand((B, B), device=target_ids.device, dtype=torch.float32)
    scores = scores.masked_fill(~same, -1.0)
    top_values, top_idx = torch.topk(scores, k=kk, dim=1)
    valid = top_values >= 0.0

    if kk < k:
        pad_n = k - kk
        top_idx = torch.cat(
            [top_idx, torch.zeros((B, pad_n), device=target_ids.device, dtype=torch.long)], dim=1
        )
        valid = torch.cat(
            [valid, torch.zeros((B, pad_n), device=target_ids.device, dtype=torch.bool)], dim=1
        )

    return top_idx[:, :k], valid[:, :k]


def select_fixed_train_references(train_indices, prot_indices_cpu, num_proteins, k, seed):
    """
    Select fixed feature references from TRAIN only. Selection is label-free.
    Returned arrays are CPU numpy arrays of shape [num_proteins, k].
    """
    rng = np.random.default_rng(seed + 7919)
    by_target = defaultdict(list)
    prot_np = np.asarray(prot_indices_cpu, dtype=np.int64)

    for pair_idx in np.asarray(train_indices, dtype=np.int64):
        by_target[int(prot_np[pair_idx])].append(int(pair_idx))

    refs = np.zeros((num_proteins, k), dtype=np.int64)
    mask = np.zeros((num_proteins, k), dtype=np.bool_)

    for p in range(num_proteins):
        ids = np.asarray(by_target.get(p, []), dtype=np.int64)
        if ids.size == 0:
            continue
        take = min(k, ids.size)
        choice = rng.choice(ids, size=take, replace=False)
        refs[p, :take] = choice
        mask[p, :take] = True

    return refs, mask


