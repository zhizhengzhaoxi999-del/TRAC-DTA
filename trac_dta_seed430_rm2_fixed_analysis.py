def complete_checkpoint_tables(output_dir, seed, tag, expected_test, fixed_refs, fixed_mask):
    """Verify matched exports and create directly reusable analysis tables."""
    read = lambda name: read_analysis_csv(os.path.join(output_dir, name))
    pred = read("test_predictions.csv")
    tcmf = read("test_tcmf_weights.csv")
    tapc = read("test_tapc_attention.csv")
    refs = read("test_references.csv")
    paired = read("paired_metrics.csv").set_index("prediction")
    if set(paired.index) != {"ABS", "FINAL"} or len(paired) != 2:
        raise ValueError(f"{tag}: expected one ABS row and one FINAL row")
    keys = ["pair_index", "drug_index", "protein_index", "seed", "checkpoint"]
    for name, frame in (("predictions", pred), ("TCMF", tcmf), ("TAPC", tapc), ("references", refs)):
        if not np.array_equal(frame.pair_index.to_numpy(), expected_test):
            raise ValueError(f"{tag}/{name}: test pair IDs/order are incomplete or mismatched")
        if not frame[keys].equals(pred[keys]):
            raise ValueError(f"{tag}/{name}: sample identities are mismatched")
        if not (frame.seed.eq(seed).all() and frame.checkpoint.eq(tag).all()):
            raise ValueError(f"{tag}/{name}: wrong seed or checkpoint label")
    for frame in (tcmf, tapc):
        if not np.array_equal(frame.y_true.to_numpy(), pred.y_true.to_numpy()):
            raise ValueError(f"{tag}: diagnostic labels do not match prediction labels")
    proteins = pred.protein_index.to_numpy(dtype=np.int64)
    if not np.array_equal(pred.n_valid_refs.to_numpy(), fixed_mask[proteins].sum(1)):
        raise ValueError(f"{tag}: reference counts differ from the saved training reference bank")
    for j in range(fixed_refs.shape[1]):
        expected = np.where(fixed_mask[proteins, j], fixed_refs[proteins, j], -1)
        if not np.array_equal(refs[f"ref_{j+1}_pair_index"].to_numpy(), expected):
            raise ValueError(f"{tag}: reference slot {j+1} differs from the saved bank")
    identity_error = float(np.max(np.abs(pred.y_pred_final - pred.y_pred_abs - pred.gate * pred.delta)))
    if identity_error > 2e-5:
        raise ValueError(f"{tag}: correction identity failed after CSV round trip")
    metric_cols = ["MSE", "CI", "rm2", "Spearman", "Pearson", "MAE", "R2",
                   "WithinTargetCI_pair_weighted", "WithinTargetCI_macro"]
    for path, column in (("ABS", "y_pred_abs"), ("FINAL", "y_pred_final")):
        actual = metrics_numpy(pred.y_true.to_numpy(), pred[column].to_numpy())
        for metric in ("MSE", "CI", "rm2", "Spearman", "Pearson", "MAE", "R2"):
            if not np.isclose(actual[metric], paired.loc[path, metric], atol=1e-12, rtol=1e-10, equal_nan=True):
                raise ValueError(f"{tag}/{path}: saved {metric} does not match exported predictions")

    rows = []
    for metric in metric_cols:
        before, after = float(paired.loc["ABS", metric]), float(paired.loc["FINAL", metric])
        lower = metric in ("MSE", "MAE")
        benefit = before - after if lower else after - before
        rows.append({"seed": seed, "checkpoint": tag, "metric": metric,
                     "better_direction": "lower" if lower else "higher",
                     "ABS": before, "FINAL": after, "FINAL_minus_ABS": after - before,
                     "improvement_positive_is_better": benefit,
                     "relative_improvement_percent": 100 * benefit / abs(before) if before else np.nan})
    changes = pd.DataFrame(rows)
    save_csv(changes, os.path.join(output_dir, "paired_metric_changes.csv"))

    joined = pred.copy()
    for frame in (tcmf, tapc):
        for column in frame.columns:
            if column not in joined.columns:
                joined[column] = frame[column].to_numpy()
    save_csv(joined, os.path.join(output_dir, "all_sample_diagnostics.csv"))

    weight_cols = ["drug_plm_weight", "drug_graph_weight", "protein_plm_weight", "protein_graph_weight"]
    weight_rows = []
    for column in weight_cols:
        values = tcmf[column].to_numpy()
        weight_rows.append({"seed": seed, "checkpoint": tag, "weight": column,
                            "mean": float(np.mean(values)), "sample_level_std": float(np.std(values)),
                            "min": float(np.min(values)), "q25": float(np.quantile(values, .25)),
                            "median": float(np.median(values)), "q75": float(np.quantile(values, .75)),
                            "max": float(np.max(values))})
    weight_summary = pd.DataFrame(weight_rows)
    save_csv(weight_summary, os.path.join(output_dir, "tcmf_weight_summary.csv"))
    variation_rows = []
    for entity, opposite in (("drug", "protein"), ("protein", "drug")):
        for index, group in tcmf.groupby(f"{entity}_index", sort=True):
            values = group[f"{entity}_plm_weight"].to_numpy()
            variation_rows.append({"entity_type": entity, "entity_index": int(index),
                                   "entity_id": group[f"{entity}_id"].iloc[0], "n_pairs": len(group),
                                   "n_opposite_entities": int(group[f"{opposite}_index"].nunique()),
                                   "plm_weight_mean": float(np.mean(values)),
                                   "plm_weight_std": float(np.std(values)),
                                   "plm_weight_range": float(np.ptp(values))})
    save_csv(pd.DataFrame(variation_rows), os.path.join(output_dir, "tcmf_within_entity_variation.csv"))

    proto_cols = [col for col in tapc.columns if col.startswith("prototype_weight_")]
    raw = tapc[proto_cols].to_numpy(dtype=np.float64)
    normalized = raw / raw.sum(1, keepdims=True)
    if (not np.isfinite(normalized).all() or np.any(normalized < 0)
            or not np.allclose(normalized.sum(1), 1, atol=1e-12)):
        raise ValueError(f"{tag}: TAPC attention is invalid")
    if not tapc.normalized_entropy.between(-1e-12, 1 + 1e-12).all():
        raise ValueError(f"{tag}: normalized TAPC entropy lies outside [0, 1]")
    # These are post-hoc observed-label bins. They do not define prototype meanings
    # and are never used for training, prediction, or configuration selection.
    bins = pd.qcut(tapc.y_true, q=5, labels=False, duplicates="drop")
    if bins.isna().all():
        bins = pd.Series(np.zeros(len(tapc), dtype=int), index=tapc.index)
    attention_frame = pd.DataFrame(normalized, columns=proto_cols)
    affinity_rows = []
    for bin_id in sorted(bins.dropna().unique()):
        mask = bins.eq(bin_id)
        group = tapc.loc[mask]
        affinity_rows.append({"affinity_bin": int(bin_id) + 1, "n_pairs": len(group),
                              "observed_affinity_min": group.y_true.min(),
                              "observed_affinity_max": group.y_true.max(),
                              "normalized_entropy_mean": group.normalized_entropy.mean(),
                              **attention_frame.loc[mask].mean().to_dict()})
    save_csv(pd.DataFrame(affinity_rows), os.path.join(output_dir, "tapc_by_observed_affinity_bin.csv"))
    by_target = pd.concat([tapc[["protein_index", "protein_id"]], attention_frame], axis=1)
    target_attention = by_target.groupby(["protein_index", "protein_id"], sort=True)[proto_cols].mean()
    target_attention["n_pairs"] = by_target.groupby(["protein_index", "protein_id"], sort=True).size()
    save_csv(target_attention.reset_index(), os.path.join(output_dir, "tapc_by_target_normalized.csv"))
    usage = read("tapc_prototype_usage.csv")
    if (not np.allclose(usage.mean_attention.to_numpy(), normalized.mean(0), atol=1e-12)
            or not np.isclose(usage.top1_fraction.sum(), 1, atol=1e-12)):
        raise ValueError(f"{tag}: TAPC usage summary does not match individual attention rows")
    write_json(os.path.join(output_dir, "tapc_usage_summary.json"), {
        "n_prototypes": len(proto_cols),
        "mean_normalized_entropy": float(tapc.normalized_entropy.mean()),
        "mean_effective_prototypes": float(tapc.effective_prototypes.mean()),
        "fraction_nonzero_representation_update": float((tapc.update_l2 > 0).mean()),
        "mean_relative_update_l2": float(tapc.relative_update_l2.mean()),
        "largest_mean_attention": float(usage.mean_attention.max()),
        "largest_top1_fraction": float(usage.top1_fraction.max()),
        "prototype_semantics": "Latent anchors, not predefined affinity levels or binding sites.",
    })
    check = {"seed": seed, "checkpoint": tag, "n_test_records": len(pred),
             "matched_pair_ids": True, "saved_reference_bank_matches": True,
             "metrics_recomputed_from_exported_predictions": True,
             "max_final_identity_error": identity_error,
             "TCMF_complete": True, "TAPC_complete": True, "ABS_FINAL_complete": True}
    write_json(os.path.join(output_dir, "export_check.json"), check)
    return changes, weight_summary, check


