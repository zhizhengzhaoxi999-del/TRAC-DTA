class RobustProjector(nn.Module):
    def __init__(self, in_dim, out_dim):
        super().__init__()
        bottleneck = 256
        self.proj = nn.Sequential(
            nn.LayerNorm(in_dim),
            nn.Linear(in_dim, bottleneck),
            nn.GELU(),
            nn.LayerNorm(bottleneck),
            nn.Dropout(DROPOUT),
            nn.Linear(bottleneck, out_dim),
            nn.LayerNorm(out_dim),
        )

    def forward(self, x):
        return self.proj(x)


class GINLayer(nn.Module):
    def __init__(self, ind, outd):
        super().__init__()
        self.ind = ind
        self.outd = outd
        self.mlp = nn.Sequential(
            nn.Linear(ind, outd),
            nn.LayerNorm(outd),
            nn.GELU(),
            nn.Dropout(DROPOUT),
            nn.Linear(outd, outd),
            nn.LayerNorm(outd),
            nn.GELU(),
        )
        self.eps = nn.Parameter(torch.tensor(0.0))

    def forward(self, x, adj_norm, node_mask):
        if x.dim() == 2:
            x = x.unsqueeze(0)
        mask = node_mask.unsqueeze(-1)
        x = x * mask
        neigh = torch.matmul(adj_norm, x)
        out = neigh + self.eps * x
        B, N, C = out.shape
        out = self.mlp(out.reshape(-1, C)).reshape(B, N, -1)
        if self.ind == self.outd:
            out = out + x
        return out * mask


class GATLayer(nn.Module):
    def __init__(self, ind, outd, dropout=DROPOUT, alpha=0.2):
        super().__init__()
        self.fc = nn.Linear(ind, outd, bias=False)
        self.attn_l = nn.Linear(outd, 1, bias=False)
        self.attn_r = nn.Linear(outd, 1, bias=False)
        self.leaky = nn.LeakyReLU(alpha)
        self.dropout = nn.Dropout(dropout)
        self.norm = nn.LayerNorm(outd)
        self.use_residual = ind == outd

    def forward(self, x, adj_bool, node_mask):
        if x.dim() == 2:
            x = x.unsqueeze(0)
        mask = node_mask.unsqueeze(-1)
        x = x * mask
        h = self.fc(x)
        e_l = self.attn_l(h)
        e_r = self.attn_r(h).permute(0, 2, 1)
        e = self.leaky(e_l + e_r)

        node_pair_mask = node_mask.unsqueeze(1) * node_mask.unsqueeze(2)
        allowed = (adj_bool > 0) & node_pair_mask.bool()
        e_masked = e.masked_fill(~allowed, _SOFTMAX_NEG_INF)

        attention = F.softmax(e_masked, dim=-1)
        attention = torch.nan_to_num(attention, nan=0.0)
        out = torch.matmul(self.dropout(attention), h)
        if self.use_residual:
            out = out + x
        return self.norm(out * mask)


class GIN_GAT_Encoder(nn.Module):
    def __init__(self, in_dim, hid_dim, out_dim):
        super().__init__()
        self.gin1 = GINLayer(in_dim, hid_dim)
        self.gin2 = GINLayer(hid_dim, hid_dim)
        self.gat = GATLayer(hid_dim, out_dim)

    def forward(self, x, adj_norm, adj_bool, node_mask):
        x = self.gin1(x, adj_norm, node_mask)
        x = self.gin2(x, adj_norm, node_mask)
        x = self.gat(x, adj_bool, node_mask)
        return F.elu(x)


class AttentionPooling(nn.Module):
    def __init__(self, in_dim):
        super().__init__()
        hidden = max(8, in_dim // 2)
        self.attn = nn.Sequential(nn.Linear(in_dim, hidden), nn.Tanh(), nn.Linear(hidden, 1))

    def forward(self, x, mask=None):
        scores = self.attn(x).squeeze(-1)
        if mask is not None:
            scores = scores.masked_fill(mask == 0, _SOFTMAX_NEG_INF)
        weights = F.softmax(scores, dim=1).unsqueeze(-1)
        if mask is not None:
            weights = weights * mask.unsqueeze(-1)
        return torch.sum(x * weights, dim=1)


class InteractivePooling(nn.Module):
    """Light cross-modal pooling retained to keep the absolute backbone strong.
    DCR and the old AdaptiveGatedFusion remain removed.
    """
    def __init__(self, dim):
        super().__init__()
        self.W_self = nn.Linear(dim, dim)
        self.W_ctx = nn.Linear(dim, dim)
        self.v = nn.Linear(dim, 1, bias=False)

    def forward(self, x_self, x_context_global, mask=None):
        h = torch.tanh(self.W_self(x_self) + self.W_ctx(x_context_global).unsqueeze(1))
        scores = self.v(h).squeeze(-1)
        if mask is not None:
            scores = scores.masked_fill(mask == 0, _SOFTMAX_NEG_INF)
        w = F.softmax(scores, dim=1).unsqueeze(-1)
        if mask is not None:
            w = w * mask.unsqueeze(-1)
        return torch.sum(x_self * w, dim=1)


class TargetConditionedModalityFusion(nn.Module):
    """
    Target-Conditioned Modality Fusion (TCMF).

    Fuses an entity's PLM and graph vectors while using the opposite entity's
    PLM+graph context to decide which modality is more informative for the
    current drug-target pair. This is sample-local and has no batch-wise DCR.

    The context is explicitly multimodal: [context_plm, context_graph].
    Hence drug fusion sees BOTH protein PLM and protein graph information, and
    protein fusion sees BOTH drug PLM and drug graph information.
    """
    def __init__(self, dim):
        super().__init__()
        self.dim = dim
        self.context_net = nn.Sequential(
            nn.LayerNorm(dim * 2),
            nn.Linear(dim * 2, dim),
            nn.GELU(),
            nn.Dropout(DROPOUT * 0.5),
            nn.Linear(dim, dim),
            nn.LayerNorm(dim),
        )
        self.plm_norm = nn.LayerNorm(dim)
        self.graph_norm = nn.LayerNorm(dim)
        self.ctx_norm = nn.LayerNorm(dim)
        self.plm_score = nn.Sequential(
            nn.Linear(dim * 2, dim), nn.GELU(), nn.Linear(dim, 1)
        )
        self.graph_score = nn.Sequential(
            nn.Linear(dim * 2, dim), nn.GELU(), nn.Linear(dim, 1)
        )
        self.interaction = nn.Sequential(
            nn.Linear(dim, dim), nn.GELU(), nn.Dropout(DROPOUT), nn.Linear(dim, dim)
        )
        self.alpha_inter = nn.Parameter(torch.tensor(0.0))
        self.out_norm = nn.LayerNorm(dim)

        # Non-persistent diagnostics: no parameters/buffers or training changes.
        self.capture_analysis = False
        self.analysis_weights = None

    def forward(self, plm_vec, graph_vec, context_plm, context_graph):
        ctx = self.context_net(torch.cat([context_plm, context_graph], dim=-1))
        p = self.plm_norm(plm_vec)
        g = self.graph_norm(graph_vec)
        c = self.ctx_norm(ctx)

        score_p = self.plm_score(torch.cat([p, c], dim=-1))
        score_g = self.graph_score(torch.cat([g, c], dim=-1))
        weights = F.softmax(torch.cat([score_p, score_g], dim=-1), dim=-1)
        if self.capture_analysis:
            self.analysis_weights = weights.detach().float().cpu()
        fused = weights[:, :1] * plm_vec + weights[:, 1:] * graph_vec

        # Cross-modal agreement term. Zero-initialized residual scale keeps the
        # first optimization steps conservative instead of forcing a new branch.
        inter = self.interaction(p * g)
        fused = fused + torch.tanh(self.alpha_inter) * inter
        return self.out_norm(fused)


class TargetConditionedAffinityPrototypeCalibration(nn.Module):
    """Target-Conditioned Affinity Prototype Calibration (TAPC).

    TCMF answers which PLM/graph modality should be trusted for this D-P pair.
    TAPC answers where the resulting pair representation lies relative to a small,
    stable set of target-conditioned affinity prototypes.

    Unlike DCR, this module performs NO sample-to-sample / batch-wise attention.
    For a fixed (drug, protein) input its prototype context is independent of the
    other samples in the mini-batch.

    The residual scale eta is initialized at zero. Because no LayerNorm is applied
    after the residual addition, TAPC is an exact identity mapping at initialization.
    """
    def __init__(self, pair_dim, target_dim, num_prototypes=8, proto_dim=128):
        super().__init__()
        self.num_prototypes = num_prototypes
        self.proto_dim = proto_dim

        # Global affinity anchors. The current protein conditions these anchors
        # before the D-P pair is positioned against them.
        self.prototypes = nn.Parameter(torch.empty(num_prototypes, proto_dim))
        nn.init.normal_(self.prototypes, mean=0.0, std=0.02)

        self.pair_norm = nn.LayerNorm(pair_dim)
        self.target_norm = nn.LayerNorm(target_dim)
        self.query = nn.Linear(pair_dim, proto_dim, bias=False)
        self.key = nn.Linear(proto_dim, proto_dim, bias=False)

        # Protein-conditioned FiLM parameters for the prototype bank.
        self.target_condition = nn.Sequential(
            nn.Linear(target_dim, proto_dim * 2),
            nn.GELU(),
            nn.Linear(proto_dim * 2, proto_dim * 2),
        )

        self.context_to_pair = nn.Sequential(
            nn.LayerNorm(proto_dim),
            nn.Linear(proto_dim, pair_dim),
            nn.GELU(),
            nn.Dropout(DROPOUT * 0.5),
            nn.Linear(pair_dim, pair_dim),
        )
        self.calibration = nn.Sequential(
            nn.LayerNorm(pair_dim * 2),
            nn.Linear(pair_dim * 2, pair_dim),
            nn.GELU(),
            nn.Dropout(DROPOUT * 0.5),
            nn.Linear(pair_dim, pair_dim),
        )
        self.eta = nn.Parameter(torch.tensor(0.0))
        self.capture_analysis = False
        self.analysis_snapshot = None

    def forward(self, pair_z, target_z):
        # pair_z: [B, pair_dim], target_z: [B, target_dim]
        q = self.query(self.pair_norm(pair_z))                       # [B, R]
        gamma, beta = self.target_condition(self.target_norm(target_z)).chunk(2, dim=-1)
        gamma = torch.tanh(gamma)
        beta = torch.tanh(beta)

        base = self.prototypes.unsqueeze(0)                          # [1, M, R]
        conditioned = (1.0 + gamma.unsqueeze(1)) * base + beta.unsqueeze(1)
        k = self.key(conditioned)                                    # [B, M, R]
        scores = (q.unsqueeze(1) * k).sum(dim=-1) / math.sqrt(self.proto_dim)
        weights = F.softmax(scores, dim=-1)                          # [B, M]
        proto_context = (weights.unsqueeze(-1) * conditioned).sum(dim=1)

        ctx = self.context_to_pair(proto_context)
        delta = self.calibration(torch.cat([pair_z, ctx], dim=-1))
        refined = pair_z + torch.tanh(self.eta) * delta
        if self.capture_analysis:
            # Actual applied update, including rounding in the original TAPC path.
            update = refined.float() - pair_z.float()
            self.analysis_snapshot = {
                "weights": weights.detach().float().cpu(),
                "update_l2": update.detach().norm(dim=-1).cpu(),
                "pair_l2": pair_z.detach().float().norm(dim=-1).cpu(),
            }
        return refined


class InteractionAwareGatedFusion(nn.Module):
    """Pair fusion over [D, P, D*P, |D-P|] with a learned residual gate."""
    def __init__(self, dim, out_dim):
        super().__init__()
        in_dim = dim * 4
        self.pre = nn.Sequential(
            nn.LayerNorm(in_dim), nn.Linear(in_dim, out_dim), nn.GELU(), nn.Dropout(DROPOUT)
        )
        self.gate = nn.Sequential(nn.Linear(in_dim, out_dim), nn.Sigmoid())
        self.skip = nn.Linear(dim * 2, out_dim)
        self.out = nn.Sequential(nn.Linear(out_dim, out_dim), nn.GELU(), nn.LayerNorm(out_dim))

    def forward(self, drug_vec, prot_vec):
        interaction = torch.cat([drug_vec, prot_vec, drug_vec * prot_vec, torch.abs(drug_vec - prot_vec)], dim=-1)
        h = self.pre(interaction)
        g = self.gate(interaction)
        fused = g * h + (1.0 - g) * self.skip(torch.cat([drug_vec, prot_vec], dim=-1))
        return self.out(fused)


