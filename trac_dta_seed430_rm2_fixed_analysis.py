@torch.no_grad()
def build_reference_bank(raw_model, fixed_refs_np, fixed_mask_np, G, num_proteins):
    """
    Encode fixed TRAIN interactions once for the current model state.
    The bank contains pair embeddings only; training affinity labels never enter
    the forward prediction path.
    """
    raw_model.eval()
    bank = torch.zeros((num_proteins, REL_K, PAIR_DIM), device=DEVICE, dtype=AMP_TYPE)
    bank_mask = torch.tensor(fixed_mask_np, device=DEVICE, dtype=torch.bool)

    records = []
    for p in range(num_proteins):
        for slot in range(REL_K):
            if fixed_mask_np[p, slot]:
                records.append((p, slot, int(fixed_refs_np[p, slot])))

    for start in range(0, len(records), EVAL_BATCH_SIZE):
        chunk = records[start:start + EVAL_BATCH_SIZE]
        pair_indices = torch.tensor([r[2] for r in chunk], device=DEVICE, dtype=torch.long)
        inputs, _, _ = make_inputs(pair_indices, G)
        with autocast("cuda", dtype=AMP_TYPE, enabled=torch.cuda.is_available()):
            _, _, z_pair = raw_model.encode_only(**inputs)
        for local_i, (p, slot, _) in enumerate(chunk):
            bank[p, slot] = z_pair[local_i].to(AMP_TYPE)

    return bank, bank_mask


@torch.no_grad()
def evaluate(model, raw_model, eval_indices, G, fixed_refs_np, fixed_mask_np, num_proteins, desc="Eval", calibration_scale=1.0):
    raw_model.eval(); model.eval()
    bank, bank_mask = build_reference_bank(raw_model, fixed_refs_np, fixed_mask_np, G, num_proteins)
    finals, absolutes, trues, gates, deltas, relconfs = [], [], [], [], [], []
    eval_indices_gpu = torch.tensor(eval_indices, device=DEVICE, dtype=torch.long)
    for start in range(0, len(eval_indices), EVAL_BATCH_SIZE):
        b_idx = eval_indices_gpu[start:start + EVAL_BATCH_SIZE]
        inputs, y, bp = make_inputs(b_idx, G)
        external_ref_z = bank[bp]; ref_valid = bank_mask[bp]
        with autocast("cuda", dtype=AMP_TYPE, enabled=torch.cuda.is_available()):
            out = model(**inputs, ref_valid=ref_valid, ref_idx=None,
                        external_ref_z=external_ref_z, calibration_scale=calibration_scale)
            final_pred, abs_pred = out[0], out[1]
            rel_logits, gate, delta = out[5], out[6], out[7]
            valid_f = ref_valid.to(rel_logits.dtype)
            rel_conf = (torch.sigmoid(rel_logits) * valid_f).sum(1) / valid_f.sum(1).clamp_min(1.0)
        finals.append(final_pred.detach()); absolutes.append(abs_pred.detach()); trues.append(y.detach())
        gates.append(gate.detach()); deltas.append(delta.detach()); relconfs.append(rel_conf.detach())
    final_all=torch.cat(finals); abs_all=torch.cat(absolutes); true_all=torch.cat(trues)
    gate_all=torch.cat(gates).float(); delta_all=torch.cat(deltas).float(); relconf_all=torch.cat(relconfs).float()
    fm=compute_metrics(true_all, final_all); am=compute_metrics(true_all, abs_all)
    metrics=dict(fm)
    metrics.update({
        "AbsMSE":am["MSE"], "AbsCI":am["CI"], "AbsR2":am["R2"], "Absrm2":am["rm2"],
        "AbsPearson":am["Pearson"], "AbsSpearman":am["Spearman"],
        "GainMSE":am["MSE"]-fm["MSE"], "GainCI":fm["CI"]-am["CI"],
        "GateMean":gate_all.mean().item(), "GateStd":gate_all.std(unbiased=False).item(),
        "GateMin":gate_all.min().item(), "GateMax":gate_all.max().item(),
        "DeltaAbsMean":delta_all.abs().mean().item(), "DeltaStd":delta_all.std(unbiased=False).item(),
        "DeltaAbsMax":delta_all.abs().max().item(), "RelConfMean":relconf_all.mean().item(),
        "RelConfStd":relconf_all.std(unbiased=False).item(),
    })
    print(f"[{desc}] ABS   | MSE {am['MSE']:.4f} | CI {am['CI']:.4f} | rm2 {am['rm2']:.4f} | Pearson {am['Pearson']:.4f} | Spearman {am['Spearman']:.4f}")
    print(f"[{desc}] FINAL | MSE {fm['MSE']:.4f} | CI {fm['CI']:.4f} | rm2 {fm['rm2']:.4f} | Pearson {fm['Pearson']:.4f} | Spearman {fm['Spearman']:.4f}")
    print(f"[{desc}] GAIN  | MSE {metrics['GainMSE']:+.4f} | CI {metrics['GainCI']:+.4f} | "
          f"Gate {metrics['GateMean']:.3f}±{metrics['GateStd']:.3f} | "
          f"|Delta| {metrics['DeltaAbsMean']:.4f} (max {metrics['DeltaAbsMax']:.4f}) | "
          f"RelConf {metrics['RelConfMean']:.3f}±{metrics['RelConfStd']:.3f}")
    return metrics


def write_json(path, value):
    """Write strict JSON; undefined metrics are null, not nonstandard NaN."""
    def clean(x):
        if isinstance(x, dict):
            return {str(k): clean(v) for k, v in x.items()}
        if isinstance(x, (list, tuple)):
            return [clean(v) for v in x]
        if isinstance(x, np.ndarray):
            return clean(x.tolist())
        if isinstance(x, np.generic):
            return clean(x.item())
        if isinstance(x, float) and not math.isfinite(x):
            return None
        return x
    with open(path, "w", encoding="utf-8") as f:
        json.dump(clean(value), f, ensure_ascii=False, indent=2, allow_nan=False)


