def run_cycle(seed, run_idx, data):
    del run_idx
    drugs, prots, d_plm, d_mask, p_plm, p_mask, d_idx, p_idx, aff = data
    seed_everything(seed)

    total_len = len(aff)
    indices = np.arange(total_len)
    np.random.shuffle(indices)
    split_1 = int(0.1 * total_len)
    split_2 = int(0.2 * total_len)
    te_idx = indices[:split_1]
    val_idx = indices[split_1:split_2]
    tr_idx = indices[split_2:]
    print(f"[SPLIT] train/val/test = {len(tr_idx)}/{len(val_idx)}/{len(te_idx)} | Seed={seed}")

    G = prepare_resident_data(d_plm, d_mask, p_plm, p_mask, d_idx, p_idx, aff, drugs, prots)
    prot_indices_cpu = p_idx.cpu().numpy()
    sampler = TargetGroupedBatchSampler(tr_idx, prot_indices_cpu, batch_size=BATCH_SIZE,
                                         group_size=TARGET_GROUP_SIZE, seed=seed)
    steps_per_epoch = len(sampler)
    fixed_refs_np, fixed_mask_np = select_fixed_train_references(
        tr_idx, prot_indices_cpu, num_proteins=len(prots), k=REL_K, seed=seed)
    split_path = os.path.join(RUN_CACHE_DIR, f"split_and_references_seed_{seed}.npz")
    if EXPORT_ONLY:
        with np.load(split_path) as saved:
            for name, current in (("train_indices", tr_idx), ("validation_indices", val_idx),
                                  ("test_indices", te_idx), ("fixed_references", fixed_refs_np),
                                  ("fixed_reference_mask", fixed_mask_np)):
                if not np.array_equal(saved[name], current):
                    raise ValueError(f"Saved {name} differs from reconstructed seed-{seed} experiment")
        with open(os.path.join(RUN_CACHE_DIR, "run_manifest.json"), encoding="utf-8") as f:
            manifest = json.load(f)
        if manifest["source_data_sha256"] != source_data_hashes():
            raise ValueError("Source data changed since this run was trained")
    else:
        save_run_provenance(seed, tr_idx, val_idx, te_idx, fixed_refs_np, fixed_mask_np)
    for protein_index in range(len(prots)):
        valid_references = fixed_refs_np[protein_index, fixed_mask_np[protein_index]]
        if not np.all(prot_indices_cpu[valid_references] == protein_index):
            raise ValueError("A fixed reference belongs to a different target")
    print(f"[V3-TCMF-TAPC] Two-stage training | Stage1={STAGE1_EPOCHS} ep | Stage2={STAGE2_EPOCHS} ep | K={REL_K}")

    raw_model = TRAC_DTA_Model().to(DEVICE)
    model = raw_model
    if ENABLE_COMPILE and not EXPORT_ONLY and hasattr(torch, "compile"):
        try:
            print(f"[INFO] torch.compile ON | mode={COMPILE_MODE} | dynamic={COMPILE_DYNAMIC}")
            model = torch.compile(raw_model, mode=COMPILE_MODE, dynamic=COMPILE_DYNAMIC,
                                  fullgraph=COMPILE_FULLGRAPH)
        except Exception as e:
            print(f"[WARN] torch.compile failed: {e}. Falling back to eager mode.")
            model = raw_model

    stage1_best_path = os.path.join(RUN_CACHE_DIR, f"stage1_best_abs_mse_seed_{seed}.pth")
    stage1_best_ci_path = os.path.join(RUN_CACHE_DIR, f"stage1_best_abs_ci_seed_{seed}.pth")
    stage2_best_mse_path = os.path.join(RUN_CACHE_DIR, f"stage2_best_final_mse_seed_{seed}.pth")
    stage2_best_ci_path = os.path.join(RUN_CACHE_DIR, f"stage2_best_final_ci_seed_{seed}.pth")

    if EXPORT_ONLY:
        return finish_test_exports(raw_model, te_idx, G, fixed_refs_np, fixed_mask_np,
                                   len(prots), seed, stage2_best_mse_path, stage2_best_ci_path)
    training_history = []

    # ---------------- Stage 1: strong absolute predictor ----------------
    print("\n========== STAGE 1: ABSOLUTE AFFINITY LEARNING ==========")
    # Relation/calibration parameters are excluded from Stage-1 optimizer.
    stage1_params = []
    for name, param in raw_model.named_parameters():
        is_relation = name.startswith("relation_encoder.") or name.startswith("rel_heads.") or name.startswith("calibration.")
        param.requires_grad = not is_relation
        if param.requires_grad:
            stage1_params.append(param)

    try:
        opt1 = torch.optim.AdamW(stage1_params, lr=STAGE1_MAX_LR, weight_decay=WEIGHT_DECAY, fused=True)
    except Exception:
        opt1 = torch.optim.AdamW(stage1_params, lr=STAGE1_MAX_LR, weight_decay=WEIGHT_DECAY)
    sch1 = OneCycleLR(opt1, max_lr=STAGE1_MAX_LR, epochs=STAGE1_EPOCHS,
                      steps_per_epoch=steps_per_epoch, pct_start=ONECYCLE_PCT_START)
    scaler1 = GradScaler(enabled=USE_SCALER)
    best_abs_mse = float("inf")
    best_abs_ci = -float("inf")
    best_abs_mse_state = None
    best_abs_ci_state = None
    stale = 0

    for epoch in range(STAGE1_EPOCHS):
        raw_model.train(); model.train()
        loss_sum = mse_sum = rank_sum = cl_sum = 0.0; steps = 0
        pbar = tqdm(sampler.iter_epoch(epoch), total=steps_per_epoch, leave=False,
                    desc=f"S1 Ep {epoch+1}")
        for batch_np in pbar:
            b_idx = torch.tensor(batch_np, device=DEVICE, dtype=torch.long)
            inputs, y, _ = make_inputs(b_idx, G)
            opt1.zero_grad(set_to_none=True)
            with autocast("cuda", dtype=AMP_TYPE, enabled=torch.cuda.is_available()):
                abs_pred, z_d, z_p = model(**inputs, ref_valid=None, absolute_only=True)
                mse = F.mse_loss(abs_pred, y)
                rank = pairwise_ranking_loss(abs_pred, y)
                cl = supcon_loss(z_d, y) + supcon_loss(z_p, y) if STAGE1_ALPHA_CL > 0 else abs_pred.new_tensor(0.0)
                loss = STAGE1_ALPHA_MSE*mse + STAGE1_ALPHA_RANK*rank + STAGE1_ALPHA_CL*cl
            if USE_SCALER:
                scaler1.scale(loss).backward(); scaler1.unscale_(opt1)
                torch.nn.utils.clip_grad_norm_(stage1_params, GRAD_CLIP)
                scaler1.step(opt1); scaler1.update()
            else:
                loss.backward(); torch.nn.utils.clip_grad_norm_(stage1_params, GRAD_CLIP); opt1.step()
            sch1.step()
            loss_sum += loss.item(); mse_sum += mse.item(); rank_sum += rank.item(); cl_sum += cl.item(); steps += 1

        # calibration_scale=0 makes FINAL exactly ABS for validation.
        vm = evaluate(model, raw_model, val_idx, G, fixed_refs_np, fixed_mask_np, len(prots),
                      desc=f"S1-Val Ep{epoch+1:03d}", calibration_scale=0.0)
        mse_imp = vm["AbsMSE"] < best_abs_mse
        ci_imp = vm["AbsCI"] > best_abs_ci
        if mse_imp:
            best_abs_mse = float(vm["AbsMSE"])
            best_abs_mse_state = {k:v.detach().cpu().clone() for k,v in raw_model.state_dict().items()}
            torch.save(best_abs_mse_state, stage1_best_path)
        if ci_imp:
            best_abs_ci = float(vm["AbsCI"])
            best_abs_ci_state = {k:v.detach().cpu().clone() for k,v in raw_model.state_dict().items()}
            torch.save(best_abs_ci_state, stage1_best_ci_path)
        record_training_history(training_history, "Stage1", epoch + 1, vm)
        stale = 0 if (mse_imp or ci_imp) else stale + 1
        marker=(" *BEST-MSE*" if mse_imp else "")+(" *BEST-CI*" if ci_imp else "")
        print(f"S1 Ep {epoch+1:03d} | LR {opt1.param_groups[0]['lr']:.2e} | Loss {loss_sum/steps:.4f} | "
              f"MSE {mse_sum/steps:.4f} | Rank {rank_sum/steps:.4f} | CL {cl_sum/steps:.4f} | "
              f"Val ABS MSE/CI {vm['AbsMSE']:.4f}/{vm['AbsCI']:.4f} | BestMSE {best_abs_mse:.4f} | BestCI {best_abs_ci:.4f}{marker}")
        if stale >= STAGE1_PATIENCE:
            print("[Stage1] Early Stopping."); break

    # CI is the primary metric for the relational paper, so Stage 2 starts from
    # the validation-selected Best-CI absolute checkpoint (never from test selection).
    if best_abs_ci_state is None:
        best_abs_ci_state = torch.load(stage1_best_ci_path, map_location="cpu")
    raw_model.load_state_dict(best_abs_ci_state, strict=True)
    print(f"[Stage1 DONE] Best ABS Val MSE={best_abs_mse:.4f} | Best ABS Val CI={best_abs_ci:.4f} | Stage2 init=Best-CI")

    # ---------------- Stage 2: frozen-ABS residual learning ----------------
    print("\n========== STAGE 2: RELATIONAL RESIDUAL REFINEMENT ==========")
    relation_prefixes = ("relation_encoder.", "rel_heads.", "calibration.")
    stage2_params = []
    for name, param in raw_model.named_parameters():
        trainable = name.startswith(relation_prefixes)
        param.requires_grad = trainable
        if trainable: stage2_params.append(param)
    print(f"[Stage2] Frozen absolute predictor; trainable relation params={sum(p.numel() for p in stage2_params):,}")

    try:
        opt2 = torch.optim.AdamW(stage2_params, lr=STAGE2_MAX_LR, weight_decay=WEIGHT_DECAY, fused=True)
    except Exception:
        opt2 = torch.optim.AdamW(stage2_params, lr=STAGE2_MAX_LR, weight_decay=WEIGHT_DECAY)
    sch2 = OneCycleLR(opt2, max_lr=STAGE2_MAX_LR, epochs=STAGE2_EPOCHS,
                      steps_per_epoch=steps_per_epoch, pct_start=ONECYCLE_PCT_START)
    scaler2 = GradScaler(enabled=USE_SCALER)
    best_mse=float("inf"); best_ci=-float("inf"); best_mse_state=None; best_ci_state=None; stale=0

    for epoch in range(STAGE2_EPOCHS):
        # Keep whole model in eval mode so frozen backbone dropout cannot inject noise;
        # explicitly enable train mode only for the three trainable relation modules.
        raw_model.eval(); model.eval()
        raw_model.relation_encoder.train(); raw_model.rel_heads.train(); raw_model.calibration.train()
        loss_sum=res_sum=dir_sum=rel_sum=frank_sum=gate_sum=delta_sum=0.0; steps=0
        pbar=tqdm(sampler.iter_epoch(10000+epoch), total=steps_per_epoch, leave=False,
                  desc=f"S2 Ep {epoch+1}")
        for batch_np in pbar:
            b_idx=torch.tensor(batch_np, device=DEVICE, dtype=torch.long)
            inputs,y,bp=make_inputs(b_idx,G)
            ref_idx,ref_valid=build_inbatch_reference_indices(bp,REL_K)
            opt2.zero_grad(set_to_none=True)
            with autocast("cuda", dtype=AMP_TYPE, enabled=torch.cuda.is_available()):
                pred,abs_pred,z_d,z_p,dir_logits,rel_logits,gate,delta=model(
                    **inputs, ref_valid=ref_valid, ref_idx=ref_idx, external_ref_z=None,
                    calibration_scale=1.0)
                # Explicit residual target. Since ABS is frozen, minimizing this is
                # equivalent to refining FINAL without allowing backbone co-adaptation.
                residual_target=(y.float()-abs_pred.detach().float())
                residual_pred=gate.float()*delta.float()
                residual_loss=F.mse_loss(residual_pred,residual_target)
                direction_loss,reliability_loss=relational_aux_losses(
                    dir_logits,rel_logits,y,ref_idx,ref_valid)
                # Module 3: directly reward FINAL ordering repair, focusing on
                # same-target pairs the frozen ABS predictor misorders/is unsure about.
                final_rank_loss=error_aware_final_ranking_loss(
                    pred,abs_pred,y,ref_idx,ref_valid,ERROR_AWARE_MARGIN)
                loss=(STAGE2_ALPHA_RESIDUAL*residual_loss +
                      STAGE2_ALPHA_DIRECTION*direction_loss +
                      STAGE2_ALPHA_RELIABILITY*reliability_loss +
                      STAGE2_ALPHA_FINAL_RANK*final_rank_loss)
            if USE_SCALER:
                scaler2.scale(loss).backward(); scaler2.unscale_(opt2)
                torch.nn.utils.clip_grad_norm_(stage2_params,GRAD_CLIP)
                scaler2.step(opt2); scaler2.update()
            else:
                loss.backward(); torch.nn.utils.clip_grad_norm_(stage2_params,GRAD_CLIP); opt2.step()
            sch2.step()
            loss_sum+=loss.item(); res_sum+=residual_loss.item(); dir_sum+=direction_loss.item(); rel_sum+=reliability_loss.item(); frank_sum+=final_rank_loss.item()
            gate_sum+=gate.detach().float().mean().item(); delta_sum+=delta.detach().abs().float().mean().item(); steps+=1

        vm=evaluate(model,raw_model,val_idx,G,fixed_refs_np,fixed_mask_np,len(prots),
                    desc=f"S2-Val Ep{epoch+1:03d}",calibration_scale=1.0)
        mse_imp=vm["MSE"]<best_mse; ci_imp=vm["CI"]>best_ci
        if mse_imp:
            best_mse=float(vm["MSE"]); best_mse_state={k:v.detach().cpu().clone() for k,v in raw_model.state_dict().items()}; torch.save(best_mse_state,stage2_best_mse_path)
        if ci_imp:
            best_ci=float(vm["CI"]); best_ci_state={k:v.detach().cpu().clone() for k,v in raw_model.state_dict().items()}; torch.save(best_ci_state,stage2_best_ci_path)
        record_training_history(training_history, "Stage2", epoch + 1, vm)
        stale=0 if (mse_imp or ci_imp) else stale+1
        marker=(" *BEST-MSE*" if mse_imp else "")+(" *BEST-CI*" if ci_imp else "")
        print(f"S2 Ep {epoch+1:03d} | LR {opt2.param_groups[0]['lr']:.2e} | Loss {loss_sum/steps:.4f} | "
              f"Residual {res_sum/steps:.4f} | Dir {dir_sum/steps:.4f} | Rel {rel_sum/steps:.4f} | FinalRank {frank_sum/steps:.4f} | "
              f"Gate {gate_sum/steps:.3f} | |Delta| {delta_sum/steps:.4f} | "
              f"Val ABS {vm['AbsMSE']:.4f}/{vm['AbsCI']:.4f} | FINAL {vm['MSE']:.4f}/{vm['CI']:.4f} | "
              f"GAIN {vm['GainMSE']:+.4f}/{vm['GainCI']:+.4f}{marker}")
        if (epoch+1)%TEST_MONITOR_INTERVAL==0:
            evaluate(model,raw_model,te_idx,G,fixed_refs_np,fixed_mask_np,len(prots),
                     desc=f"S2-TEST-MONITOR Ep{epoch+1:03d}",calibration_scale=1.0)
        if stale>=STAGE2_PATIENCE:
            print("[Stage2] Early Stopping."); break

    return finish_test_exports(raw_model, te_idx, G, fixed_refs_np, fixed_mask_np,
                               len(prots), seed, stage2_best_mse_path, stage2_best_ci_path)

