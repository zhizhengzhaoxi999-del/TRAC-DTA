def write_analysis_tables(arrays, output_dir, seed, tag, drug_ids, protein_ids,
                          parameter_info, prototype_bank):
    """Pure NumPy/Pandas exports. Every diagnostic row keeps its test pair ID."""
    os.makedirs(output_dir, exist_ok=True)
    a = {k: np.asarray(v) for k, v in arrays.items()}
    n = len(a["pair_index"])
    if not n or any(len(v) != n for v in a.values()):
        raise ValueError("Diagnostic arrays have mismatched sample counts")
    if len(np.unique(a["pair_index"])) != n:
        raise ValueError("Duplicate test pair IDs")
    for key in ("y_true", "y_pred_abs", "y_pred_final", "gate", "delta", "rel_conf",
                "drug_weights", "protein_weights", "tapc_weights"):
        if not np.isfinite(a[key]).all():
            raise ValueError(f"Nonfinite diagnostic values in {key}")
    for key in ("drug_weights", "protein_weights", "tapc_weights"):
        w = a[key]
        if np.any(w < 0) or np.any(w > 1) or not np.allclose(w.sum(1), 1, atol=0.015, rtol=0):
            raise ValueError(f"Invalid softmax weights in {key}")

    base = pd.DataFrame({
        "pair_index": a["pair_index"].astype(np.int64),
        "drug_index": a["drug_index"].astype(np.int64),
        "protein_index": a["protein_index"].astype(np.int64),
        "drug_id": [drug_ids[int(i)] for i in a["drug_index"]],
        "protein_id": [protein_ids[int(i)] for i in a["protein_index"]],
        "seed": seed, "checkpoint": tag, "split": "test",
        "y_true": a["y_true"],
    })
    pred = base.copy()
    for key in ("y_pred_abs", "y_pred_final", "gate", "delta", "rel_conf", "n_valid_refs"):
        pred[key] = a[key]
    pred["correction"] = pred.y_pred_final - pred.y_pred_abs
    pred["abs_error_abs"] = np.abs(pred.y_true - pred.y_pred_abs)
    pred["abs_error_final"] = np.abs(pred.y_true - pred.y_pred_final)
    pred["squared_error_abs"] = (pred.y_true - pred.y_pred_abs)**2
    pred["squared_error_final"] = (pred.y_true - pred.y_pred_final)**2
    pred["squared_error_gain"] = pred.squared_error_abs - pred.squared_error_final
    pred["improved"] = pred.squared_error_gain > 0
    identity_error = float(np.max(np.abs(pred.correction - pred.gate * pred.delta)))
    if identity_error > 2e-5:
        raise ValueError(f"FINAL differs from ABS + gate*delta: max error={identity_error}")
    save_csv(pred, os.path.join(output_dir, "test_predictions.csv"))

    tcmf = base.copy()
    for branch, key in (("drug", "drug_weights"), ("protein", "protein_weights")):
        tcmf[f"{branch}_plm_weight"] = a[key][:, 0]
        tcmf[f"{branch}_graph_weight"] = a[key][:, 1]
    save_csv(tcmf, os.path.join(output_dir, "test_tcmf_weights.csv"))
    weight_cols = ["drug_plm_weight", "drug_graph_weight",
                   "protein_plm_weight", "protein_graph_weight"]
    for entity, opposite in (("drug", "protein"), ("protein", "drug")):
        groups = tcmf.groupby([f"{entity}_index", f"{entity}_id"], sort=True)
        summary = groups[weight_cols].agg(["mean", "std"])
        summary.columns = [f"{k}_{stat}" for k, stat in summary.columns]
        summary["n_pairs"] = groups.size()
        summary[f"n_{opposite}s"] = groups[f"{opposite}_index"].nunique()
        save_csv(summary.reset_index(), os.path.join(output_dir, f"tcmf_by_{entity}.csv"))

    tapc = base.copy()
    raw_w = a["tapc_weights"].astype(np.float64)
    # Keep actual AMP-rounded weights in the per-pair CSV. Normalize a copy only
    # for entropy/usage statistics to compensate for softmax rounding in AMP.
    w = raw_w / raw_w.sum(1, keepdims=True)
    m = w.shape[1]
    proto_cols = [f"prototype_weight_{j+1}" for j in range(m)]
    for j, col in enumerate(proto_cols):
        tapc[col] = raw_w[:, j]
    entropy = -(w * np.log(np.clip(w, 1e-15, 1))).sum(1)
    top = w.argmax(1)
    tapc["attention_entropy"] = entropy
    tapc["normalized_entropy"] = entropy / math.log(m) if m > 1 else 0.0
    tapc["effective_prototypes"] = np.exp(entropy)
    tapc["top_prototype"] = top + 1
    tapc["max_attention"] = w.max(1)
    tapc["update_l2"] = a["tapc_update_l2"]
    tapc["base_pair_l2"] = a["tapc_pair_l2"]
    tapc["relative_update_l2"] = a["tapc_update_l2"] / np.maximum(a["tapc_pair_l2"], 1e-12)
    save_csv(tapc, os.path.join(output_dir, "test_tapc_attention.csv"))
    usage = pd.DataFrame({"prototype": np.arange(1, m + 1),
                          "mean_attention": w.mean(0), "std_attention": w.std(0),
                          "top1_fraction": np.bincount(top, minlength=m) / n})
    save_csv(usage, os.path.join(output_dir, "tapc_prototype_usage.csv"))
    by_target = tapc.groupby(["protein_index", "protein_id"], sort=True)
    target_attention = by_target[proto_cols + ["normalized_entropy", "relative_update_l2"]].mean()
    target_attention["n_pairs"] = by_target.size()
    save_csv(target_attention.reset_index(), os.path.join(output_dir, "tapc_by_target.csv"))
    np.savez_compressed(os.path.join(output_dir, "tapc_prototype_bank.npz"),
                        prototypes=np.asarray(prototype_bank))

    references = base[["pair_index", "drug_index", "protein_index", "seed", "checkpoint"]].copy()
    for j in range(a["reference_indices"].shape[1]):
        for key, name in (("reference_indices", "pair_index"),
                          ("reference_reliability", "reliability"),
                          ("reference_weights", "aggregation_weight"),
                          ("reference_direction_probability", "direction_probability")):
            references[f"ref_{j+1}_{name}"] = a[key][:, j]
    save_csv(references, os.path.join(output_dir, "test_references.csv"))

    target_rows = []
    for protein_index, group in pred.groupby("protein_index", sort=True):
        y = group.y_true.to_numpy()
        row = {"protein_index": int(protein_index), "protein_id": group.protein_id.iloc[0],
               "n_pairs": len(group), "n_distinct_affinities": len(np.unique(y))}
        for path, col in (("ABS", "y_pred_abs"), ("FINAL", "y_pred_final")):
            metrics = metrics_numpy(y, group[col].to_numpy())
            correct, comparable = concordance_components(y, group[col].to_numpy())
            row.update({f"{path}_{k}": v for k, v in metrics.items()})
            row[f"{path}_concordant_score"] = correct
            row["comparable_pairs"] = comparable
        row["MSE_gain"] = row["ABS_MSE"] - row["FINAL_MSE"]
        row["CI_change"] = row["FINAL_CI"] - row["ABS_CI"] if comparable else float("nan")
        target_rows.append(row)
    target_frame = pd.DataFrame(target_rows)
    save_csv(target_frame, os.path.join(output_dir, "per_target_metrics.csv"))

    gate_bins = pd.qcut(pred.gate, q=5, labels=False, duplicates="drop")
    if gate_bins.isna().all():
        gate_bins = pd.Series(np.zeros(n, dtype=int), index=pred.index)
    bin_rows = []
    for bin_id, group in pred.assign(gate_bin=gate_bins).groupby("gate_bin", sort=True):
        bin_rows.append({"gate_bin": int(bin_id) + 1, "n_pairs": len(group),
                         "gate_min": group.gate.min(), "gate_max": group.gate.max(),
                         "gate_mean": group.gate.mean(),
                         "mean_abs_correction": group.correction.abs().mean(),
                         "ABS_MSE": group.squared_error_abs.mean(),
                         "FINAL_MSE": group.squared_error_final.mean(),
                         "MSE_gain": group.squared_error_gain.mean(),
                         "fraction_improved": group.improved.mean(),
                         "rel_conf_mean": group.rel_conf.mean()})
    save_csv(pd.DataFrame(bin_rows), os.path.join(output_dir, "gate_bins.csv"))

    am = metrics_numpy(pred.y_true.to_numpy(), pred.y_pred_abs.to_numpy())
    fm = metrics_numpy(pred.y_true.to_numpy(), pred.y_pred_final.to_numpy())
    valid_targets = target_frame.comparable_pairs > 0
    for path, metrics in (("ABS", am), ("FINAL", fm)):
        eligible = target_frame.loc[valid_targets, "comparable_pairs"].sum()
        metrics["WithinTargetCI_pair_weighted"] = (
            float(target_frame.loc[valid_targets, f"{path}_concordant_score"].sum() / eligible)
            if eligible else float("nan"))
        metrics["WithinTargetCI_macro"] = float(target_frame.loc[valid_targets, f"{path}_CI"].mean())
    save_csv(pd.DataFrame([{"prediction": "ABS", **am}, {"prediction": "FINAL", **fm}]),
             os.path.join(output_dir, "paired_metrics.csv"))
    write_json(os.path.join(output_dir, "analysis_summary.json"), {
        "seed": seed, "checkpoint": tag, "n_test_records": n,
        "ABS": am, "FINAL": fm,
        "MSE_gain": am["MSE"] - fm["MSE"],
        "MSE_relative_reduction": (am["MSE"] - fm["MSE"]) / am["MSE"] if am["MSE"] else None,
        "fraction_improved": float(pred.improved.mean()),
        "fraction_worsened": float((pred.squared_error_gain < 0).mean()),
        "max_final_identity_error": identity_error,
        "parameters": parameter_info,
        "notes": ["TCMF/TAPC rows and ABS/FINAL rows share identical pair_index order.",
                  "TCMF weights describe the softmax mixture; agreement-residual scales are reported separately.",
                  "TAPC per-pair weights retain AMP precision; entropy/usage normalize a float64 copy.",
                  "TAPC update_l2 measures the actual refined-minus-input representation after AMP rounding.",
                  "Prototype IDs are latent anchors, not predefined affinity intervals.",
                  "Global CI and within-target CI are separate diagnostics.",
                  "Counts describe one seed-430 evaluation, not a multi-run mean or standard deviation."],
    })
    out = dict(fm)
    out.update({f"Abs{k}": v for k, v in am.items()})
    out.update({"GainMSE": am["MSE"] - fm["MSE"], "GainCI": fm["CI"] - am["CI"],
                "GateMean": float(pred.gate.mean()), "GateStd": float(pred.gate.std(ddof=0)),
                "GateMin": float(pred.gate.min()), "GateMax": float(pred.gate.max()),
                "DeltaAbsMean": float(pred.delta.abs().mean()),
                "DeltaStd": float(pred.delta.std(ddof=0)), "DeltaAbsMax": float(pred.delta.abs().max()),
                "RelConfMean": float(pred.rel_conf.mean()), "RelConfStd": float(pred.rel_conf.std(ddof=0))})
    return out, pred.y_pred_abs.to_numpy(copy=True)


@torch.no_grad()
def export_test_analysis(raw_model, test_indices, G, fixed_refs_np, fixed_mask_np,
                         num_proteins, seed, tag, checkpoint_path):
    raw_model.eval()
    capture_modules = (raw_model.d_fuse, raw_model.p_fuse, raw_model.tapc)
    for module in capture_modules:
        module.capture_analysis = False
    # Reference-bank encoding must not enter the query-only diagnostic tables.
    bank, bank_mask = build_reference_bank(raw_model, fixed_refs_np, fixed_mask_np, G, num_proteins)
    chunks = defaultdict(list)
    for module in capture_modules:
        module.capture_analysis = True
    try:
        for start in tqdm(range(0, len(test_indices), EVAL_BATCH_SIZE), desc=f"Export {tag}"):
            b_idx = torch.as_tensor(test_indices[start:start + EVAL_BATCH_SIZE], device=DEVICE, dtype=torch.long)
            inputs, y, bp = make_inputs(b_idx, G)
            ref_valid = bank_mask[bp]
            with autocast("cuda", dtype=AMP_TYPE, enabled=torch.cuda.is_available()):
                out = raw_model(**inputs, ref_valid=ref_valid, ref_idx=None,
                                external_ref_z=bank[bp], calibration_scale=1.0)
                valid = ref_valid.to(out[5].dtype)
                reliability = torch.sigmoid(out[5]) * valid
                confidence = reliability.sum(1) / valid.sum(1).clamp_min(1.0)
                ref_weights = reliability / reliability.sum(1, keepdim=True).clamp_min(1e-6)
                direction = torch.sigmoid(out[4])
            target_np = bp.detach().cpu().numpy()
            refs = np.where(fixed_mask_np[target_np], fixed_refs_np[target_np], -1)
            tensors = {"pair_index": b_idx, "drug_index": G["idx_d"][b_idx], "protein_index": bp,
                       "y_true": y, "y_pred_final": out[0], "y_pred_abs": out[1],
                       "gate": out[6], "delta": out[7], "rel_conf": confidence,
                       "n_valid_refs": ref_valid.sum(1), "reference_reliability": reliability,
                       "reference_weights": ref_weights, "reference_direction_probability": direction}
            for key, tensor in tensors.items():
                value = tensor.detach().cpu()
                if value.is_floating_point():
                    value = value.float()
                chunks[key].append(value.numpy())
            chunks["reference_indices"].append(refs)
            chunks["drug_weights"].append(raw_model.d_fuse.analysis_weights.numpy())
            chunks["protein_weights"].append(raw_model.p_fuse.analysis_weights.numpy())
            snap = raw_model.tapc.analysis_snapshot
            chunks["tapc_weights"].append(snap["weights"].numpy())
            chunks["tapc_update_l2"].append(snap["update_l2"].numpy())
            chunks["tapc_pair_l2"].append(snap["pair_l2"].numpy())
    finally:
        for module in capture_modules:
            module.capture_analysis = False
        raw_model.d_fuse.analysis_weights = None
        raw_model.p_fuse.analysis_weights = None
        raw_model.tapc.analysis_snapshot = None
    arrays = {k: np.concatenate(v, axis=0) for k, v in chunks.items()}
    if not np.array_equal(arrays["pair_index"], np.asarray(test_indices)):
        raise ValueError("Test row order changed during export")
    with open(os.path.join(DATA_PATH, "drug_smiles.json"), encoding="utf-8") as f:
        drug_ids = sorted(json.load(f))
    with open(os.path.join(DATA_PATH, "protein_seq.json"), encoding="utf-8") as f:
        protein_ids = sorted(json.load(f))
    info = {"checkpoint_path": os.path.abspath(checkpoint_path), "inference": "eager eval with original AMP",
            "final_composition_dtype": "float32", "drug_agreement_scale": float(torch.tanh(raw_model.d_fuse.alpha_inter).cpu()),
            "protein_agreement_scale": float(torch.tanh(raw_model.p_fuse.alpha_inter).cpu()),
            "tapc_eta_raw": float(raw_model.tapc.eta.cpu()),
            "tapc_eta_effective": float(torch.tanh(raw_model.tapc.eta).cpu()),
            "n_prototypes": raw_model.tapc.num_prototypes}
    output_dir = os.path.join(RUN_CACHE_DIR, f"analysis_seed_{seed}", tag)
    return write_analysis_tables(arrays, output_dir, seed, tag, drug_ids, protein_ids, info,
                                 raw_model.tapc.prototypes.detach().float().cpu().numpy())


def finish_test_exports(raw_model, test_indices, G, fixed_refs_np, fixed_mask_np,
                         num_proteins, seed, stage2_best_mse_path, stage2_best_ci_path):
    print("\n========== MATCHED FINAL TEST AND ANALYSIS EXPORT ==========")
    results, first_abs = {}, None
    max_abs_difference = 0.0
    for tag, path in (("Best-MSE", stage2_best_mse_path), ("Best-CI", stage2_best_ci_path)):
        state = torch.load(path, map_location="cpu")
