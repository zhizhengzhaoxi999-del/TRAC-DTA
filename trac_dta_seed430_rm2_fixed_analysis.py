class TargetConditionedRelationEncoder(nn.Module):
    """
    Explicitly represents R_ij^P rather than using ranking only at loss level.
    Input for each anchor/reference pair:
      [z_i, z_j, z_i-z_j, |z_i-z_j|, z_i*z_j, z_P]
    """

    def __init__(self, pair_dim, target_dim, hidden_dim, rel_dim):
        super().__init__()
        in_dim = pair_dim * 5 + target_dim
        self.net = nn.Sequential(
            nn.LayerNorm(in_dim),
            nn.Linear(in_dim, hidden_dim),
            nn.GELU(),
            nn.Dropout(DROPOUT),
            nn.Linear(hidden_dim, rel_dim),
            nn.LayerNorm(rel_dim),
            nn.GELU(),
        )

    def forward(self, anchor_z, ref_z, target_z):
        # anchor_z: [B, D], ref_z: [B, K, D], target_z: [B, T]
        K = ref_z.size(1)
        a = anchor_z.unsqueeze(1).expand(-1, K, -1)
        t = target_z.unsqueeze(1).expand(-1, K, -1)
        x = torch.cat(
            [a, ref_z, a - ref_z, torch.abs(a - ref_z), a * ref_z, t],
            dim=-1,
        )
        return self.net(x)


class RelationalHeads(nn.Module):
    def __init__(self, rel_dim):
        super().__init__()
        hidden = max(64, rel_dim // 2)
        self.direction = nn.Sequential(
            nn.Linear(rel_dim, hidden), nn.GELU(), nn.Dropout(DROPOUT * 0.5), nn.Linear(hidden, 1)
        )
        self.reliability = nn.Sequential(
            nn.Linear(rel_dim, hidden), nn.GELU(), nn.Dropout(DROPOUT * 0.5), nn.Linear(hidden, 1)
        )

    def forward(self, rel_z):
        direction_logits = self.direction(rel_z).squeeze(-1)
        reliability_logits = self.reliability(rel_z).squeeze(-1)
        return direction_logits, reliability_logits


class RelationalCalibration(nn.Module):
    """Reliability-aware small residual corrector.

    The relation branch is intentionally conservative:
      y_final = y_abs + cal_scale * gate * delta
      gate = relation_confidence * learned_gate
    There is no tanh hard bound, which avoids the V1.1 |Delta|=0.75 saturation.
    """

    def __init__(self, pair_dim, rel_dim):
        super().__init__()
        self.trunk = nn.Sequential(
            nn.LayerNorm(pair_dim + rel_dim),
            nn.Linear(pair_dim + rel_dim, 256),
            nn.GELU(),
            nn.Dropout(DROPOUT),
            nn.Linear(256, 128),
            nn.GELU(),
        )
        self.delta_head = nn.Linear(128, 1)
        self.gate_head = nn.Linear(128, 1)
        nn.init.zeros_(self.delta_head.weight)
        nn.init.zeros_(self.delta_head.bias)
        nn.init.zeros_(self.gate_head.weight)
        nn.init.constant_(self.gate_head.bias, -1.0)

    def forward(self, pair_z, rel_agg, relation_confidence, has_reference):
        # detach protects the strong absolute backbone from calibration shortcuts;
        # the absolute MSE/rank/CL path still trains the backbone normally.
        h = self.trunk(torch.cat([pair_z.detach(), rel_agg], dim=-1))
        delta = DELTA_SCALE * self.delta_head(h).squeeze(-1)
        learned_gate = torch.sigmoid(self.gate_head(h).squeeze(-1))
        gate = relation_confidence.detach() * learned_gate
        gate = gate * has_reference.to(gate.dtype)
        return delta, gate


class TRAC_DTA_Model(nn.Module):
    def __init__(self):
        super().__init__()
        self.d_proj = RobustProjector(PLM_DRUG_DIM, GNN_OUT)
        self.p_proj = RobustProjector(PLM_PROT_DIM, GNN_OUT)
        self.d_gnn = GIN_GAT_Encoder(DRUG_FEAT_DIM_RAW, GNN_HID, GNN_OUT)
        self.p_gnn = GIN_GAT_Encoder(PROT_FEAT_DIM_RAW, GNN_HID, GNN_OUT)
        self.pool = AttentionPooling(GNN_OUT)
        self.inter_d = InteractivePooling(GNN_OUT)
        self.inter_p = InteractivePooling(GNN_OUT)

        self.d_fuse = TargetConditionedModalityFusion(GNN_OUT)
        self.p_fuse = TargetConditionedModalityFusion(GNN_OUT)
        self.pair_encoder = InteractionAwareGatedFusion(GNN_OUT, PAIR_DIM)
        self.tapc = TargetConditionedAffinityPrototypeCalibration(
            PAIR_DIM, GNN_OUT, TAPC_NUM_PROTOTYPES, TAPC_PROTO_DIM
        )

        self.absolute_head = nn.Sequential(
            nn.Linear(PAIR_DIM, 512),
            nn.LayerNorm(512),
            nn.GELU(),
            nn.Dropout(DROPOUT),
            nn.Linear(512, 256),
            nn.LayerNorm(256),
            nn.GELU(),
            nn.Dropout(DROPOUT),
            nn.Linear(256, 1),
        )

        self.relation_encoder = TargetConditionedRelationEncoder(
            PAIR_DIM, GNN_OUT, REL_HIDDEN, REL_DIM
        )
        self.rel_heads = RelationalHeads(REL_DIM)
        self.calibration = RelationalCalibration(PAIR_DIM, REL_DIM)

    def encode_only(
        self,
        d_plm,
        d_mask,
        p_plm,
        p_mask,
        dx,
        dadj_norm,
        dadj_bool,
        dnode_mask,
        px,
        padj_norm,
        padj_bool,
        pnode_mask,
    ):
        ed = self.d_proj(d_plm)
        ep = self.p_proj(p_plm)
        gd = self.d_gnn(dx, dadj_norm, dadj_bool, dnode_mask)
        gp = self.p_gnn(px, padj_norm, padj_bool, pnode_mask)

        # Cross-modal contexts make the absolute branch substantially stronger than
        # independent pooling, while avoiding DCR and the old adaptive gated fusion.
        ctx_d = self.pool(ed, d_mask)
        ctx_p = self.pool(ep, p_mask)
        ctx_gd = self.pool(gd, dnode_mask)
        ctx_gp = self.pool(gp, pnode_mask)
        d_plm_vec = self.inter_d(ed, ctx_p, d_mask)
        p_plm_vec = self.inter_p(ep, ctx_d, p_mask)
        d_graph_vec = self.inter_d(gd, ctx_gp, dnode_mask)
        p_graph_vec = self.inter_p(gp, ctx_gd, pnode_mask)

        # TCMF: modality selection is conditioned on the opposite entity's
        # complete multimodal context. Protein graph features are therefore
        # explicitly present when fusing the drug, and vice versa.
        z_d = self.d_fuse(d_plm_vec, d_graph_vec, p_plm_vec, p_graph_vec)
        z_p = self.p_fuse(p_plm_vec, p_graph_vec, d_plm_vec, d_graph_vec)
        # Explicit interaction-aware gated pair fusion.
        z_pair = self.pair_encoder(z_d, z_p)
        # TAPC positions the D-P pair against protein-conditioned affinity
        # prototypes. No batch/sample context is used.
        z_pair = self.tapc(z_pair, z_p)
        return z_d, z_p, z_pair

    def forward(
        self,
        d_plm,
        d_mask,
        p_plm,
        p_mask,
        dx,
        dadj_norm,
        dadj_bool,
        dnode_mask,
        px,
        padj_norm,
        padj_bool,
        pnode_mask,
        ref_valid,
        ref_idx=None,
        external_ref_z=None,
        calibration_scale=1.0,
        absolute_only=False,
    ):
        z_d, z_p, z_pair = self.encode_only(
            d_plm,
            d_mask,
            p_plm,
            p_mask,
            dx,
            dadj_norm,
            dadj_bool,
            dnode_mask,
            px,
            padj_norm,
            padj_bool,
            pnode_mask,
        )

        abs_pred = self.absolute_head(z_pair).squeeze(-1)

        # Stage 1 trains only the absolute predictor. Skipping the relational
        # branch avoids unnecessary relation computation and guarantees that
        # Stage-1 gradients cannot enter relation/calibration modules.
        if absolute_only:
            return abs_pred, z_d, z_p

        if external_ref_z is None:
            if ref_idx is None:
                raise ValueError("ref_idx is required when external_ref_z is None")
            ref_z = z_pair[ref_idx]
        else:
            ref_z = external_ref_z

        # Protected relation branch: auxiliary relation objectives do not reshape
        # the strong absolute backbone. The relation modules themselves still train.
        rel_anchor = z_pair.detach()
        rel_ref = ref_z.detach()
        rel_target = z_p.detach()
        rel_z = self.relation_encoder(rel_anchor, rel_ref, rel_target)
        direction_logits, reliability_logits = self.rel_heads(rel_z)

        valid_f = ref_valid.to(reliability_logits.dtype)
        reliability = torch.sigmoid(reliability_logits) * valid_f
        valid_count = valid_f.sum(dim=1).clamp_min(1.0)
        relation_confidence = reliability.sum(dim=1) / valid_count
        denom = reliability.sum(dim=1, keepdim=True).clamp_min(1e-6)
        rel_agg = (rel_z * reliability.unsqueeze(-1)).sum(dim=1) / denom

        has_reference = ref_valid.any(dim=1)
        rel_agg = rel_agg * has_reference.unsqueeze(-1).to(rel_agg.dtype)
        delta, gate = self.calibration(z_pair, rel_agg, relation_confidence, has_reference)
        # Keep small corrections when the backbone runs under BF16/FP16 AMP.
        final_pred = abs_pred.float() + float(calibration_scale) * gate.float() * delta.float()

        return (
            final_pred,
            abs_pred,
            z_d,
            z_p,
            direction_logits,
            reliability_logits,
            gate,
            delta,
        )


