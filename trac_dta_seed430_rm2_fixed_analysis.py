def source_data_hashes():
    hashes = {}
    for name in ("drug_smiles.json", "protein_seq.json", "Y.txt"):
        h = hashlib.sha256()
        with open(os.path.join(DATA_PATH, name), "rb") as f:
            for block in iter(lambda: f.read(1024 * 1024), b""):
                h.update(block)
        hashes[name] = h.hexdigest()
    return hashes


