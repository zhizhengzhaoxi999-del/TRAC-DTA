def pairwise_ranking_loss(y_pred, y_true):
    B = y_true.shape[0]
    if B > 512:
        idx = torch.randperm(B, device=y_true.device)[:512]
        y_true = y_true[idx]
        y_pred = y_pred[idx]

    diff = y_true.unsqueeze(1) - y_true.unsqueeze(0)
    pred_diff = y_pred.unsqueeze(1) - y_pred.unsqueeze(0)
    loss = torch.relu(0.1 - torch.sign(diff) * pred_diff)
    mask = (diff.abs() > 1e-3).float()
    return (loss * mask).sum() / (mask.sum() + 1e-6)


def error_aware_final_ranking_loss(final_pred, abs_pred, y_true, ref_idx, ref_valid, margin=ERROR_AWARE_MARGIN):
    """Focus Stage-2 ranking pressure on same-target pairs ABS gets wrong or is unsure about.

    ref_idx is built only from same-target examples. The weighting is detached, so
    the frozen ABS branch only decides where relation refinement should focus.
    """
    ref_final = final_pred[ref_idx]
    ref_abs = abs_pred.detach()[ref_idx]
    ref_y = y_true[ref_idx]
    true_diff = y_true.unsqueeze(1) - ref_y
    sign = torch.sign(true_diff)
    valid = ref_valid & (true_diff.abs() > 1e-3)
    abs_margin = sign * (abs_pred.detach().unsqueeze(1) - ref_abs)
    # weight=1 for misordered pairs; smoothly decreases to zero once ABS margin is safe.
    focus = ((margin - abs_margin) / max(margin, 1e-6)).clamp(0.0, 1.0).detach()
    final_margin = sign * (final_pred.unsqueeze(1) - ref_final)
    per_pair = F.softplus(-final_margin)
    w = focus * valid.to(per_pair.dtype)
    return (per_pair * w).sum() / w.sum().clamp_min(1.0)


def supcon_loss(features, labels, temperature=0.07, num_bins=10):
    device = features.device
    features = F.normalize(features, dim=1)
    try:
        quantiles = torch.linspace(0.0, 1.0, steps=num_bins + 1, device=device)
        bins = torch.quantile(labels, quantiles)
        labels_q = torch.bucketize(labels, bins, right=False)
    except Exception:
        return torch.tensor(0.0, device=device)

    mask = torch.eq(labels_q.unsqueeze(1), labels_q.unsqueeze(0)).float()
    logits = torch.matmul(features, features.T) / temperature
    logits_max, _ = torch.max(logits, dim=1, keepdim=True)
    logits = logits - logits_max.detach()
    logits_mask = 1.0 - torch.eye(features.shape[0], device=device)
    mask = mask * logits_mask
    exp_logits = torch.exp(logits) * logits_mask
    log_prob = logits - torch.log(exp_logits.sum(1, keepdim=True) + 1e-6)
    mean_log_prob_pos = (mask * log_prob).sum(1) / (mask.sum(1) + 1e-6)
    valid = (mask.sum(1) > 0).float()
    if valid.sum() == 0:
        return torch.tensor(0.0, device=device)
    return -(valid * mean_log_prob_pos).sum() / (valid.sum() + 1e-6)


def relational_aux_losses(direction_logits, reliability_logits, y, ref_idx, ref_valid):
    """
    Direction supervision: y_i > y_j, weighted by the true gap-derived
    reliability during TRAINING only.

    Reliability supervision target is soft and bounded:
        q = |dy| / (|dy| + tau)
    At inference q is never used; the reliability head predicts it from features.
    """
    ref_y = y[ref_idx]
    gap = torch.abs(y.unsqueeze(1) - ref_y)
    q_target = (gap / (gap + RELIABILITY_TAU)).detach()
    dir_target = (y.unsqueeze(1) > ref_y).to(direction_logits.dtype)

    valid_f = ref_valid.to(direction_logits.dtype)
    dir_weight = q_target * valid_f

    bce = F.binary_cross_entropy_with_logits(direction_logits, dir_target, reduction="none")
    direction_loss = (bce * dir_weight).sum() / (dir_weight.sum() + 1e-6)

    reliability_pred = torch.sigmoid(reliability_logits)
    reliability_loss = (((reliability_pred - q_target) ** 2) * valid_f).sum() / (valid_f.sum() + 1e-6)

    return direction_loss, reliability_loss


def fast_concordance_index_vectorized(y_true, y_pred, max_pairs=20000):
    # Same pair-count definition, without an N-by-N allocation or subsampling.
    # KIBA validation/test size is below the old 20,000-record sampling limit.
    del max_pairs
    correct, pairs = concordance_components(y_true, y_pred)
    return float(correct / pairs) if pairs else 0.0


def concordance_components(y_true, y_pred):
    """Exact concordance; true-label ties excluded, prediction ties score 0.5."""
    t = np.asarray(y_true, dtype=np.float64).reshape(-1)
    p = np.asarray(y_pred, dtype=np.float64).reshape(-1)
    if t.size != p.size or not (np.isfinite(t).all() and np.isfinite(p).all()):
        raise ValueError("CI requires matching finite arrays")
    if t.size < 2:
        return 0.0, 0
    ranks = np.searchsorted(np.unique(p), p) + 1
    tree = np.zeros(int(ranks.max()) + 1, dtype=np.int64)

    def prefix(k):
        count = 0
        while k:
            count += int(tree[k])
            k -= k & -k
        return count

    order = np.argsort(t, kind="stable")
    correct, pairs, previous, start = 0.0, 0, 0, 0
    while start < t.size:
        end = start + 1
        while end < t.size and t[order[end]] == t[order[start]]:
            end += 1
        for idx in order[start:end]:
            rank = int(ranks[idx])
            lower = prefix(rank - 1)
            equal = prefix(rank) - lower
            correct += lower + 0.5 * equal
            pairs += previous
        for idx in order[start:end]:
            rank = int(ranks[idx])
            while rank < tree.size:
                tree[rank] += 1
                rank += rank & -rank
        previous += end - start
        start = end
    return correct, pairs


def calculate_rm2(y_true, y_pred):
    """The project's corrected DeepDTA convention, matching the PLM ablations.

    r2 = squared Pearson correlation (NOT sklearn's regression R2).
    r02 = 1 - sum((true - k*pred)**2) / sum((true - mean(true))**2),
    where k = sum(true*pred) / sum(pred**2).
    rm2 = r2 * (1 - sqrt(abs(r2**2 - r02**2))).
    Constants have undefined rm2 and are reported as NaN, never fabricated zeros.
    """
    t = np.asarray(y_true, dtype=np.float64).reshape(-1)
    p = np.asarray(y_pred, dtype=np.float64).reshape(-1)
    if len(t) != len(p) or len(t) < 2 or not (np.isfinite(t).all() and np.isfinite(p).all()):
        raise ValueError("rm2 requires matching finite arrays with at least two values")
    tc, pc = t - t.mean(), p - p.mean()
    st, sp, pp = tc @ tc, pc @ pc, p @ p
    if st == 0 or sp == 0 or pp == 0:
        return float("nan")
    r2 = float((tc @ pc)**2 / (st * sp))
    k = float(t @ p / pp)
    r02 = float(1 - ((t - k * p) @ (t - k * p)) / st)
    return float(r2 * (1 - np.sqrt(abs(r2**2 - r02**2))))


def metrics_numpy(y_true, y_pred):
    t = np.asarray(y_true, dtype=np.float64).reshape(-1)
    p = np.asarray(y_pred, dtype=np.float64).reshape(-1)
    if t.size != p.size or t.size == 0 or not (np.isfinite(t).all() and np.isfinite(p).all()):
        raise ValueError("Metrics require nonempty matching finite arrays")
    varying = t.size > 1 and np.ptp(t) > 0 and np.ptp(p) > 0
    return {
        "MSE": float(np.mean((t - p)**2)),
        "CI": fast_concordance_index_vectorized(t, p),
        "R2": float(r2_score(t, p)) if t.size > 1 else float("nan"),
        "rm2": calculate_rm2(t, p) if t.size > 1 else float("nan"),
        "Pearson": float(pearsonr(t, p)[0]) if varying else float("nan"),
        "Spearman": float(spearmanr(t, p)[0]) if varying else float("nan"),
        "MAE": float(np.mean(np.abs(t - p))),
    }


def compute_metrics(y_true, y_pred, threshold=BINARY_THRESHOLD):
    del threshold
    return metrics_numpy(y_true.detach().float().cpu().numpy(),
                         y_pred.detach().float().cpu().numpy())


